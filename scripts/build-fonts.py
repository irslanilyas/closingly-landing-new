"""Build the site's web fonts and font-derived artwork from the originals in assets-src/fonts.

Run: python scripts/build-fonts.py   (needs: pip install fonttools brotli)

Outputs (committed; the originals never ship):
  src/fonts/general-sans-{regular,medium,italic}.woff2   Latin + the punctuation the copy uses
  src/fonts/dm-sans-labels.woff2                         only the glyphs of the few DM Sans labels
  src/components/brand/wordmark-path.ts                  "Closingly" in Albert Sans 600, as one SVG path
  assets-src/fonts/cc-path.ts                            the 4px "CC" caption, drawn into public/icons/call-controls.svg
Albert Sans and Roboto Condensed are used for those two pieces of artwork only, so neither is served.
"""
from pathlib import Path

from fontTools.pens.roundingPen import RoundingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets-src" / "fonts"
OUT = ROOT / "src" / "fonts"

# Basic Latin, Latin-1 letters and the typographic marks used in the copy.
LATIN = set(range(0x20, 0x7F)) | set(range(0xA0, 0x100))
MARKS = {0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x2192, 0x2197, 0x25C9, 0x2713, 0x2726}

# Every string set in DM Sans in the design (the scope labels are uppercased by CSS).
DM_SANS_TEXT = "200 ↗ 1 2 3 JD Original scope 5-page marketing website with CMS. New client request Could we add a contact us page?"


def subset(font: TTFont, unicodes: set[int], out: Path) -> None:
    options = Options()
    options.flavor = "woff2"
    options.layout_features = ["kern", "liga", "calt", "ccmp", "locl", "mark", "mkmk"]
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6]  # copyright, family, style, version, PostScript name
    options.notdef_outline = True
    options.hinting = False  # browsers ignore TrueType hints on modern platforms; drop the bytes
    sub = Subsetter(options=options)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    font.flavor = "woff2"
    font.save(out)
    print(f"{out.relative_to(ROOT)}: {out.stat().st_size} bytes, {len(font.getGlyphOrder())} glyphs")


def instance(path: Path, **axes: float) -> TTFont:
    return instancer.instantiateVariableFont(TTFont(path), axes)


def text_path(font: TTFont, text: str, tracking_em: float) -> tuple[str, dict]:
    """One SVG path for `text`, y-down, origin at the line box top (ascender)."""
    upm = font["head"].unitsPerEm
    ascent, descent = font["hhea"].ascent, font["hhea"].descent
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    hmtx = font["hmtx"]
    pen = SVGPathPen(glyphs)
    x = 0.0
    for i, char in enumerate(text):
        name = cmap[ord(char)]
        # flip to y-down with the baseline at `ascent`; whole font units are far below a pixel
        glyphs[name].draw(TransformPen(RoundingPen(pen), (1, 0, 0, -1, x, ascent)))
        x += hmtx[name][0] + (tracking_em * upm if i < len(text) - 1 else 0)
    metrics = {"width": round(x, 2), "height": ascent - descent, "upm": upm}
    return pen.getCommands(), metrics


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    general = LATIN | MARKS
    for style in ("Regular", "Medium", "Italic"):
        subset(TTFont(SRC / f"GeneralSans-{style}.woff2"), general, OUT / f"general-sans-{style.lower()}.woff2")

    dm = instance(SRC / "DMSans.woff2", wght=400, opsz=14)
    dm_text = DM_SANS_TEXT + DM_SANS_TEXT.upper()
    subset(dm, {ord(c) for c in dm_text}, OUT / "dm-sans-labels.woff2")

    albert = instance(SRC / "AlbertSans.woff2", wght=600)
    path, m = text_path(albert, "Closingly", tracking_em=-0.07)
    (ROOT / "src" / "components" / "brand").mkdir(parents=True, exist_ok=True)
    (ROOT / "src" / "components" / "brand" / "wordmark-path.ts").write_text(
        "// Generated by scripts/build-fonts.py: \"Closingly\" in Albert Sans 600, tracked -0.07em.\n"
        f"export const WORDMARK = {{ d: {path!r}, width: {m['width']}, height: {m['height']}, upm: {m['upm']} }} as const;\n",
        encoding="utf-8",
    )
    roboto = instance(SRC / "RobotoCondensed.woff2", wght=400)
    path, m = text_path(roboto, "CC", tracking_em=0)
    cc_dir = ROOT / "assets-src" / "fonts"
    cc_dir.mkdir(parents=True, exist_ok=True)
    (cc_dir / "cc-path.ts").write_text(
        "// Generated by scripts/build-fonts.py: the \"CC\" caption in Roboto Condensed 400.\n"
        f"export const CC = {{ d: {path!r}, width: {m['width']}, height: {m['height']}, upm: {m['upm']} }} as const;\n",
        encoding="utf-8",
    )
    print("wordmark and CC paths written")


if __name__ == "__main__":
    main()
